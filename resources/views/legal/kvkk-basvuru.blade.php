    Formu formatına uygun olmalıdır.
</p>

<h2>5. Başvuruların Cevaplandırılması</h2>

<p>
    Başvurularınız, niteliğine göre en kısa sürede ve <strong>en geç 30 gün içinde
    ücretsiz olarak</strong> cevaplandırılır. Ancak işlemin ayrıca bir maliyeti
    gerektirmesi hâlinde, Kişisel Verileri Koruma Kurulu tarafından belirlenen
    tarifedeki ücret alınabilir.
</p>

<h2>6. Başvurunun Reddi</h2>

<p>
    Aşağıdaki durumlarda başvurunuz reddedilebilir:
</p>

<ul>
    <li>Kişisel verilerin işlenmesinin suç işlenmesinin önlenmesi veya soruşturulması amacıyla gerekli olması</li>
    <li>Kişisel verilerin işlenmesinin yargı organlarının yargısal faaliyetleriyle ilgili olması</li>
    <li>Başvurunuzun başkasının hakkını ihlal etmesi</li>
    <li>Başvurunuzun açıkça kötüye kullanım teşkil etmesi</li>
</ul>

