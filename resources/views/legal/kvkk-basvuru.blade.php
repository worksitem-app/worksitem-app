<h2>2. Başvuruda Bulunması Gereken Bilgiler</h2>

<ul>
    <li>Ad, soyad ve imza (yazılı başvurularda)</li>
    <li>T.C. kimlik numarası (yabancılar için pasaport numarası)</li>
    <li>Tebligata esas yerleşim yeri veya iş yeri adresi</li>
    <li>Bildirime esas elektronik posta adresi, telefon veya faks numarası</li>
    <li>Talep konusu</li>
</ul>

<h2>3. Talep Konuları</h2>

<p>KVKK'nın 11. maddesi kapsamında aşağıdaki konularda başvurabilirsiniz:</p>

<ol>
    <li>Kişisel verilerinizin işlenip işlenmediğini öğrenme</li>
    <li>İşlenmişse buna ilişkin bilgi talep etme</li>
    <li>İşlenme amacını ve amacına uygun kullanılıp kullanılmadığını öğrenme</li>
    <li>Yurt içinde / yurt dışında aktarıldığı üçüncü kişileri bilme</li>
    <li>Eksik veya yanlış işlenmişse düzeltilmesini isteme</li>
    <li>KVKK'nın 7. maddesinde öngörülen şartlar çerçevesinde silinmesini isteme</li>
    <li>Düzeltme/silme işlemlerinin aktarıldığı üçüncü kişilere bildirilmesini isteme</li>
    <li>Otomatik sistemlerce analiz edilmesi nedeniyle aleyhinize bir sonucun ortaya çıkmasına itiraz etme</li>
    <li>Kanuna aykırı işleme nedeniyle zarara uğramanız hâlinde zararın giderilmesini talep etme</li>
</ol>

<h2>4. Başvuru Formu İçeriği</h2>

<p>Başvurunuzda aşağıdaki bilgileri belirtmeniz gerekmektedir:</p>

<ul>
    <li><strong>A.</strong> Başvuru sahibinin adı, soyadı</li>
    <li><strong>B.</strong> T.C. kimlik numarası</li>
    <li><strong>C.</strong> Tebligata esas yerleşim yeri / iş yeri adresi</li>
    <li><strong>D.</strong> Bildirime esas elektronik posta, telefon, faks</li>
    <li><strong>E.</strong> Talep konusu (yukarıdaki listeden bir veya birkaçı)</li>
    <li><strong>F.</strong> Talep konusuna ilişkin bilgi ve belgeler</li>
    <li><strong>G.</strong> Başvuru yöntemi (şahsen / posta / e-posta)</li>
</ul>

<p>
    <strong>Not:</strong> Başvuru formu <a href="mailto:info@worksitem.com">info@worksitem.com</a>
