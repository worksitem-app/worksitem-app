<p>Bu koşullar, Kainta İnşaat tarafından işletilen <strong>worksitem.com</strong> sitesinde firma üyeliği için başvuran gerçek ve tüzel kişilere ("Firma") uygulanır.</p>

<h2>1. Başvuru ve onay</h2>
<p>Firma, başvuruda verdiği bilgilerin doğru ve güncel olduğunu, başvuruyu yapmaya yetkili olduğunu beyan eder. Kainta İnşaat Uzmanları başvuruyu inceler; gerekçe göstermeksizin reddetme, yayını durdurma veya kaldırma hakkı saklıdır. Telefon numarası SMS koduyla doğrulanır.</p>

<h2>2. Yayınlanan bilgiler</h2>
<p>Onaylanan firmanın adı, türü, hizmet alanları, hizmet verdiği iller/ilçe, kuruluş yılı ve tanıtım yazısı firma rehberinde yayınlanabilir. Telefon numarası sayfada açık yazılmaz; kullanıcı "Ara" veya "WhatsApp" düğmesine bastığında numaraya yönlendirilir. Vergi / TC kimlik numarası ve e-posta adresi yayınlanmaz; yalnız doğrulama ve iletişim için kullanılır.</p>

<h2>3. İçerik kuralları</h2>
<p>Firma, yanıltıcı, başkasına ait, hukuka aykırı veya üçüncü kişilerin haklarını ihlal eden içerik veremez. Worksitem, içeriği kısaltma, düzeltme veya yayından kaldırma hakkına sahiptir.</p>

<h2>4. Öne çıkan üyelik</h2>
<p>Öne çıkan üyelik isteğe bağlıdır, bir yıl sürer ve ödemesi iyzico güvenli ödeme sayfası üzerinden peşin alınır. Öne çıkan firmalar rehberde üst sırada ve rozetli gösterilir; web sitesine bağlantı verilir. Hesaplama sonuçları ve birim fiyatlar üyelikten etkilenmez. Cayma hakkı ve iade koşulları 6502 sayılı Kanun ve Mesafeli Sözleşmeler Yönetmeliği'ne göre uygulanır; hizmetin ifasına onay ile başlanmışsa cayma hakkı kullanılamaz.</p>

<h2>5. Sorumluluk</h2>
<p>Worksitem, kullanıcılar ile firmalar arasında aracı değildir; firmaların vereceği teklif, yapacağı iş, fiyat, süre ve garantilerden sorumlu değildir. Firma, kullanıcılara verdiği hizmetten ve ilgili mevzuata (vergi, iş sağlığı ve güvenliği, tüketici mevzuatı) uyumdan kendisi sorumludur.</p>

<h2>6. Kişisel veriler</h2>
<p>Yetkili kişinin kişisel verileri <a href="/legal/kvkk-aydinlatma">KVKK Aydınlatma Metni</a> kapsamında işlenir. Firma, üyeliğini ve verilerinin silinmesini her zaman <a href="/legal/kvkk-basvuru">KVKK başvuru</a> sayfası veya WhatsApp hattı üzerinden isteyebilir.</p>

<h2>7. Değişiklik</h2>
<p>Bu koşullar güncellenebilir; güncel metin bu sayfada yayınlanır. Önemli değişiklikler kayıtlı telefon veya e-posta ile bildirilir.</p>
