<h2>1. Çerez Nedir?</h2>

<p>
    Çerezler, ziyaret ettiğiniz web sitesi tarafından tarayıcınıza kaydedilen
    küçük metin dosyalarıdır. Çerezler; site tercihlerinizi hatırlamak, oturum
    yönetimi sağlamak ve site deneyimini iyileştirmek için kullanılır.
</p>

