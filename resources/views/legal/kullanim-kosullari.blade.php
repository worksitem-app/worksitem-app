<p>
    Bu koşullar, Kainta İnşaat Mimarlık &amp; Mühendislik tarafından işletilen
    <strong>worksitem.com</strong> sitesinin ve sitedeki hesaplama araçlarının kullanımına uygulanır.
    Siteyi kullanarak bu koşulları kabul etmiş sayılırsınız.
</p>

<h2>1. Hizmetin Niteliği</h2>
<p>
    Worksitem; inşaat ve tadilat projeleri için yaklaşık maliyet, metraj, ön keşif ve teknik
    ön hesaplama araçları sunar. Araçların ürettiği tüm sonuçlar <strong>bilgilendirme ve ön bütçe
    planlaması</strong> amaçlıdır; bağlayıcı bir teklif, sözleşme veya resmî belge değildir.
</p>

<h2>2. Mühendislik Hesapları</h2>
<p>
    Kolon taşıma kapasitesi, kiriş statiği, yapı dinamiği, karot dayanımı, donatı tahvili ve
    benzeri yapısal/teknik araçlar yalnızca <strong>ön kontrol ve eğitim</strong> amaçlıdır.
    Bu araçların sonuçları; yetkili bir inşaat mühendisi tarafından hazırlanan ve ilgili
    yönetmeliklere (ör. Türkiye Bina Deprem Yönetmeliği, TS 500) göre denetlenen statik proje,
    hesap raporu veya yerinde inceleme <strong>yerine geçmez</strong>. Bu sonuçlara dayanarak
    uygulama, güçlendirme, yıkım veya taşıyıcı sisteme müdahale yapılmamalıdır.
</p>

<h2>3. Fiyat ve Maliyet Verileri</h2>
<p>
    Fiyatlar; resmî birim fiyatlar (ör. Çevre, Şehircilik ve İklim Değişikliği Bakanlığı rayiçleri),
    piyasa gözlemleri ve kullanıcının girdiği bilgilerle hesaplanır. Malzeme ve işçilik fiyatları
    sık değişir; bölge, marka, kalite, erişim koşulları ve proje detayları gerçek maliyeti
    önemli ölçüde değiştirebilir. Kesin maliyet ancak yerinde keşif ve yazılı teklifle belirlenir.
</p>

<h2>4. Yapay Zekâ Çıktıları</h2>
<p>
    AI iç mekan tasarımı, otomatik keşif ve benzeri araçların çıktıları yapay zekâ tarafından
    otomatik üretilir; hatalı, eksik veya gerçekle uyuşmayan sonuçlar içerebilir. Görseller
    temsilîdir; uygulanabilirlik, malzeme ve mevzuat uygunluğu ayrıca doğrulanmalıdır.
    Yüklediğiniz görsel ve dosyaların size ait olduğunu veya kullanma hakkınız bulunduğunu,
    üçüncü kişilerin kişisel verilerini içermediğini kabul edersiniz.
</p>

<h2>5. Sorumluluğun Sınırlandırılması</h2>
<p>
    Araç sonuçlarının doğrudan veya dolaylı kullanımından doğabilecek zararlardan, yürürlükteki
    mevzuatın izin verdiği ölçüde sorumluluk kabul edilmez. Bu sınırlama; kast veya ağır ihmal
    hâllerinde ve tüketicinin emredici yasal haklarını ortadan kaldıracak şekilde uygulanmaz.
</p>
<p>
    Hesaplama sonuçları teklif değildir ve geçerlilik süresi taşımaz; fiyatlar günlük olarak ve
    ülkeye, şehre, markaya göre değişir. Araçlara girilen bilgilerin doğruluğundan ve sonuçlara
    dayanarak verilen kararlardan kullanıcı sorumludur.
</p>

<h2>5A. Yerinde Keşif ve Ödeme</h2>
<p>
    Kesin fiyat için talep edilen yerinde keşif hizmeti Kainta İnşaat tarafından verilir ve
    faturalandırılır. Keşif siparişinden önce
    <a href="/legal/kesif-on-bilgilendirme-formu">Keşif Ön Bilgilendirme Formu</a> gösterilir ve
    <a href="/legal/kesif-mesafeli-hizmet-sozlesmesi">Keşif Mesafeli Hizmet Sözleşmesi</a> onaylanır.
    Bedel, mahsup ve cayma koşulları bu belgelerde yer alır.
</p>

<h2>5B. Hizmet Bölgesi ve Hizmet Sağlayıcı (Pilot Dönem)</h2>
<p>
    Hesaplama araçları tüm Türkiye için kullanılabilir. Pilot dönemde yerinde keşif, teklif ve uygulama
    hizmetleri yalnız <strong>İstanbul</strong> il sınırları içinde ve yalnız Kainta İnşaat tarafından verilir.
    Başka illerden gelen talepler kaydedilir; bu taleplerden keşif bedeli alınmaz ve hizmet bölgesi genişlediğinde
    talep sahibine bilgi verilir. Pilot dönemde worksitem.com üzerinden başka firmalara üyelik, teklif daveti veya
    kişisel veri aktarımı yapılmaz.
</p>

<h2>6. Kabul Edilemez Kullanım</h2>
<ul>
    <li>Sitenin, araçların veya fiyat verilerinin otomatik araçlarla toplu olarak kopyalanması</li>
    <li>Hizmetin işleyişini bozacak, güvenliğini aşmaya çalışacak veya aşırı yük oluşturacak kullanım</li>
    <li>Hukuka aykırı, başkasına ait veya kişisel veri içeren içeriklerin yüklenmesi</li>
</ul>

<h2>7. Fikri Mülkiyet</h2>
<p>
    Sitenin tasarımı, yazılımı, metinleri ve derlenmiş veri tabanları Kainta İnşaat'a veya
    lisans verenlerine aittir. Resmî birim fiyatlar ilgili kamu kurumlarının yayınlarıdır.
</p>

<h2>8. Kişisel Veriler</h2>
<p>
