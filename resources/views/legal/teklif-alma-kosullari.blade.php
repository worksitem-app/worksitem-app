<p>Bu koşullar, worksitem.com platformunu işleten ve bilgileri bu sayfanın sonundaki künyede yer alan hizmet sağlayıcı ("<strong>Worksitem</strong>") ile "kayıtlı firmalardan teklif al" hizmetini kullanan kişiler ("<strong>Kullanıcı</strong>") arasında uygulanır. Hizmet Kullanıcı için ücretsizdir. Platformda hizmet veren firmalar (Worksitem'le aynı gruptan olanlar dahil) bu koşulların tarafı değildir; her biri kendi işinden sorumludur.</p>

<h2>1. Worksitem ne yapar, ne yapmaz?</h2>
<p>Worksitem, talebinizi iş koluna ve ilçenize uygun, vergi kaydı kontrol edilmiş kayıtlı firmalara ("<strong>Firma</strong>") iletir ve tekliflerini size gösterir. Worksitem bir aracı hizmet sağlayıcıdır: işi yapan, satan veya garanti eden taraf değildir; sizinle Firma arasında kurulacak sözleşmenin tarafı değildir; işin bedelini tahsil etmez.</p>

<h2>2. Teklifler</h2>
<p>Teklifler Firma'ların beyanıdır ve yerinde keşifle değişebilir. Hesaplama araçlarımızın verdiği yaklaşık maliyet de bilgi amaçlıdır. Hiçbir teklifi kabul etmek zorunda değilsiniz; talebinizi istediğiniz zaman kapatabilirsiniz. Talep 14 gün sonra kendiliğinden kapanır.</p>

<h2>3. Kişisel verilerinizin paylaşımı</h2>
<p>3.1. Talebiniz oluşturulduğunda Firma'lara yalnızca iş bilgisi, il/ilçe, başlangıç tercihi, hesapladığınız yaklaşık maliyet ve adınızın ilk kelimesi gösterilir. Açıklamanıza yazdığınız telefon, e-posta ve bağlantılar otomatik gizlenir.</p>
<p>3.2. Bir teklifi kabul ettiğinizde ve o Firma eşleşmeyi onaylayıp eşleşme bedelini ödediğinde; <strong>adınız, telefon numaranız, e-posta adresiniz (verdiyseniz) ve ilçeniz yalnızca o Firma ile paylaşılır</strong>. Bu paylaşım, sizin talebiniz üzerine ve sözleşmenin kurulması için zorunludur (KVKK m.5/2-c). Firma bu verileri yalnız sizin işiniz için kullanmakla yükümlüdür ve bu verilerin işlenmesinden ayrı bir veri sorumlusu olarak sorumludur.</p>
<p>3.3. Ayrıntılar: <a href="/legal/kvkk-aydinlatma">KVKK Aydınlatma Metni</a>. Haklarınızı <a href="/legal/kvkk-basvuru">KVKK başvuru</a> sayfasından kullanabilirsiniz.</p>

<h2>4. Önerilerimiz</h2>
<ul>
    <li>İşe başlamadan önce iş tanımı, malzeme, süre, ödeme planı ve garantiyi içeren yazılı sözleşme yapın.</li>
    <li>Ödemeyi aşamalara bölün; tamamını peşin ödemeyin.</li>
    <li>Fatura isteyin. Tüketici olarak 6502 sayılı Tüketicinin Korunması Hakkında Kanun'daki haklarınız Firma'ya karşı geçerlidir.</li>
</ul>

<h2>5. Sorumluluk</h2>
<p>İşin yapılması, kalitesi, süresi, garantisi, ödemeler ve bunlardan doğan uyuşmazlıklardan işi üstlenen Firma sorumludur. Worksitem; Firma'ların vergi kaydını kontrol eder, şikâyetleri değerlendirir ve kurallara uymayan Firma'ları askıya alır. Worksitem'in sorumluluğu, kanunen sınırlandırılamayan haller ve tüketiciye karşı emredici hükümler saklı kalmak kaydıyla, kendi aracılık hizmetinin ifasıyla sınırlıdır.</p>

<h2>6. Şikâyet</h2>
<p>Bir Firma ile yaşadığınız sorunu talep numaranızla birlikte WhatsApp ({{ config('worksitem_inspection.phone') }}) veya info@worksitem.com adresine iletin. Şikâyetiniz Firma'ya iletilir; kurallara aykırılık tespit edilirse Firma'nın üyeliği askıya alınır. Tüketici hakem heyetlerine ve tüketici mahkemelerine başvuru hakkınız saklıdır.</p>

<h2>7. Kötüye kullanım</h2>
<p>Gerçek olmayan, başkası adına veya Firma'ları yanıltmaya yönelik talep oluşturulamaz. Bir telefon numarasıyla 24 saatte en fazla 3 açık talep oluşturulabilir.</p>
