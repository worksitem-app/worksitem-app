    const [twCm,thCm]=tileDimensions();
    if(twCm<=0 || thCm<=0){alert('Geçerli karo ölçüsü girin.');return;}

    const items=surfaces();
    const netArea=items.reduce((a,s)=>a+s.area,0);
    if(netArea<=0){alert('Geçerli bir uygulama alanı girin.');return;}

    const tw=twCm/100, th=thCm/100;
    const tileArea=tw*th;
    const grout=(parseFloat($('grout').value)||0)/1000;
    const waste=Math.max(0,(parseFloat($('waste').value)||0)/100);

    let orientationA=0,orientationB=0;

    if(mode==='detailed'){
        items.forEach(s=>{
            const theoretical=Math.ceil(s.area/tileArea);
            const deducted=Math.floor((s.deduct||0)/tileArea);

            const a=Math.max(
                theoretical,
                Math.ceil((s.width+grout)/(tw+grout))*Math.ceil((s.height+grout)/(th+grout))-deducted
            );
            const b=Math.max(
                theoretical,
                Math.ceil((s.width+grout)/(th+grout))*Math.ceil((s.height+grout)/(tw+grout))-deducted
            );

            orientationA+=Math.max(theoretical,a);
            orientationB+=Math.max(theoretical,b);
        });
    }

    const theoreticalTiles=Math.ceil(netArea/tileArea);
    const layoutTiles=mode==='detailed'?Math.min(orientationA,orientationB):theoreticalTiles;
    const baseTiles=Math.max(theoreticalTiles,layoutTiles);
    const recommended=Math.ceil(baseTiles*(1+waste));
    const grossArea=recommended*tileArea;

    const perBox=parseInt($('tilesPerBox').value)||0;
    const boxPrice=parseFloat($('boxPrice').value)||0;
    const boxes=perBox>0?Math.ceil(recommended/perBox):0;
    const purchasedTiles=boxes>0?boxes*perBox:recommended;
    const leftover=Math.max(0,purchasedTiles-recommended);
    const budget=(boxes>0 && boxPrice>0)?boxes*boxPrice:0;

    /*
     * Karo bütçesi:
     * - kullanıcı gerçek kutu fiyatı girdiyse onu,
     * - aksi halde uygun internet piyasa verisini kullanır.
     */
    let tileMaterialBudget=budget;

    $('recommendedPurchase').textContent=
        recommended+' adet karo';

    $('netArea').textContent=
        trNumber(netArea,2)+' m²';

    $('grossArea').textContent=
        trNumber(grossArea,2)+' m²';
    $('baseTiles').textContent=baseTiles+' adet';
    $('recommendedTiles').textContent=recommended+' adet';
    $('boxes').textContent=boxes>0?boxes+' kutu':'—';
    $('materialBudget').textContent=
        tileMaterialBudget>0
            ? money(tileMaterialBudget)
            : '—';

    /* AUXILIARY_RESULTS_V1 */

    /* Fire */
    const fireTargetArea=netArea*(1+waste);
    const excessArea=Math.max(0,grossArea-netArea);

    $('fireTargetArea').textContent=
        fireTargetArea.toFixed(2)+' m²';

    $('excessArea').textContent=
        excessArea.toFixed(2)+' m²';


    /* Paketleme + nakliye */
    const selectedSize=
        $('tileSize').value==='custom'
            ? `${twCm}x${thCm}`
            : $('tileSize').value;

    const pkg=tilePackagingResult(
        selectedSize,
        recommended,
        grossArea,
        tileArea
    );

    $('packageGuide').textContent=pkg.packageText;
    $('shippingWeight').textContent=pkg.shippingText;

    const purchaseBoxReference=
        boxes>0
            ? boxes+' kutu'
            : (pkg.boxText || 'Kutu içeriği ürüne göre değişir');

    $('purchaseSummary').textContent=
        `${trNumber(grossArea,2)} m² satın alma alanı · `+
        `Net alan: ${trNumber(netArea,2)} m² · `+
        `Fire: %${trNumber(waste*100,0)} · `+
        `${purchaseBoxReference}`;

    if(!perBox && pkg.boxText){
        $('boxes').textContent=pkg.boxText;
    }


    /*
     * Yardımcı malzeme toplamları.
     * Fiyatı doğrulanmamış kalem otomatik olarak toplam maliyete eklenmez.
     */
    let adhesiveTotal=0;
    let groutTotal=0;
    let profileTotal=0;

    /* Yapıştırıcı */
    const adhesiveConsumption=
        parseFloat($('adhesiveConsumption').value)||0;

    const adhesiveBagKg=
        parseFloat($('adhesiveBagKg').value)||0;

    if(adhesiveConsumption>0 && adhesiveBagKg>0){

        const adhesiveKg=
            netArea*adhesiveConsumption;

        const adhesiveBags=
            Math.ceil(adhesiveKg/adhesiveBagKg);

        const adhesiveMaterialType=
            $('materialType').value;

        const adhesivePriceKey=
            adhesiveMaterialType==='ceramic' &&
            Math.abs(adhesiveBagKg-25)<0.001
                ? 'tile_adhesive_standard_25kg'
                : null;

        const adhesiveUnitPrice=
            adhesivePriceKey
                ? Number(ACCESSORY_PRICES[adhesivePriceKey]||0)
                : 0;

        adhesiveTotal=
            adhesiveUnitPrice>0
                ? adhesiveBags*adhesiveUnitPrice
                : 0;

        $('adhesiveResult').textContent=
            `${trNumber(adhesiveKg,1)} kg · `+
            `${adhesiveBags} × ${trNumber(adhesiveBagKg,1)} kg`+
            (
                adhesiveTotal>0
                    ? ` · ${money2(adhesiveTotal)}`
                    : ''
            );

    }else{
        $('adhesiveResult').textContent=
            'Ürün bilgileriyle hesaplanabilir';
    }


    /* Derz dolgusu */
    const tileThicknessMm=
        parseFloat($('tileThickness').value)||0;

    const groutDensity=
        parseFloat($('groutDensity').value)||0;

    const groutWidthMm=
        parseFloat($('grout').value)||0;

    if(
        tileThicknessMm>0 &&
        groutDensity>0 &&
        groutWidthMm>0
    ){
        /*
         * Derz tüketimi — kg/m²
         *
         * Formül tüm geometrik değerleri mm cinsinden kullanır:
         *
         * ((A+B)/(A*B)) × derz genişliği × karo kalınlığı × yoğunluk
         *
         * A/B: karo ölçüsü (mm)
         */
        const tileWidthMm=twCm*10;
        const tileHeightMm=thCm*10;

        const jointKgPerM2=
            (
                (tileWidthMm+tileHeightMm) /
                (tileWidthMm*tileHeightMm)
            )
            *
            groutWidthMm
            *
            tileThicknessMm
            *
            groutDensity;

        const jointTotal=
            jointKgPerM2*netArea;

        const groutPackKg=5;
        const groutPackPrice=
            Number(ACCESSORY_PRICES.tile_grout_5kg||0);

        if(groutPackPrice>0){
            const groutPacks=
                Math.ceil(jointTotal/groutPackKg);

            groutTotal=
                groutPacks*groutPackPrice;

            $('groutResult').textContent=
                `${trNumber(jointTotal,2)} kg · `+
                `${groutPacks} × 5 kg · `+
                `${money2(groutTotal)}`;
        }else{
            $('groutResult').textContent=
                `${trNumber(jointTotal,2)} kg`;
        }
    }else{
        $('groutResult').textContent=
            'Karo kalınlığını girerek hesaplayın';
    }


    /* Köşe profili */
    const edgeCount=
        parseInt($('profileEdges').value)||0;

    const edgeLength=
        parseFloat($('profileEdgeLength').value)||0;

    const profileLength=
        parseFloat($('profileLength').value)||0;

    let profileThickness=null;
    let profilePriceKey=null;

    if(tileThicknessMm>0 && tileThicknessMm<=8){
        profileThickness=8;
        profilePriceKey=
            'tile_profile_outside_aluminum_8mm_270cm';
    }else if(tileThicknessMm>8 && tileThicknessMm<=10){
        profileThickness=10;
        profilePriceKey=
            'tile_profile_outside_aluminum_10mm_270cm';
    }else if(tileThicknessMm>10 && tileThicknessMm<=12){
        profileThickness=12;
        profilePriceKey=
            'tile_profile_outside_aluminum_12mm_270cm';
    }

    const profileUnitPrice=
        profilePriceKey
            ? Number(ACCESSORY_PRICES[profilePriceKey]||0)
            : 0;

    const effectiveProfileLength=
        profileUnitPrice>0 ? 2.70 : profileLength;

    if(
        edgeCount>0 &&
        edgeLength>0 &&
        effectiveProfileLength>0
    ){

        const edgesPerProfile=
            Math.floor(effectiveProfileLength/edgeLength);

        if(edgesPerProfile<1){

            $('profileResult').textContent=
                'Profil boyu kenardan kısa';

        }else{

            const requiredProfiles=
                Math.ceil(edgeCount/edgesPerProfile);

            const totalEdge=
                edgeCount*edgeLength;

            const purchasedProfile=
                requiredProfiles*effectiveProfileLength;

            const profileWaste=
                Math.max(0,purchasedProfile-totalEdge);

            profileTotal=
                profileUnitPrice>0
                    ? requiredProfiles*profileUnitPrice
                    : 0;

            $('profileResult').textContent=
                `${requiredProfiles} boy`+
                (
                    profileUnitPrice>0
                        ? ` × 2,70 m · ${profileThickness} mm · ${money2(profileTotal)}`
                        : ''
                )+
                ` · ${trNumber(profileWaste,2)} m artan`;
        }

    }else{
        $('profileResult').textContent=
            'Kenar ölçülerini girerek hesaplayın';
    }

    $('detailText').textContent=
        'Hesaplama; seçtiğiniz karo ölçüsü, uygulama alanı, derz aralığı ve fire payı dikkate alınarak hazırlanmıştır. '+
        'Malzeme ihtiyacı ve uygulama maliyeti, güncel piyasa verileri ile teknik hesaplama kriterlerine göre yaklaşık olarak belirlenir. '+
        'Kesin miktar ve fiyatlar, seçilen ürün ve uygulama koşullarına göre değişebilir.';

    $('orientationText').textContent=mode==='detailed'
        ? `Yerleşim karşılaştırmasında daha düşük malzeme ihtiyacı esas alınmıştır.`
        : '';
    $('purchaseText').textContent='';

    const material=$('materialType').value;
    const size=$('tileSize').value==='custom'?`${twCm}x${thCm}`:$('tileSize').value;

    let refs=[];
    items.forEach(s=>{
        const role=officialRole(material,s.type,size);
        if(role && OFFICIAL[role]){
            refs.push({role,data:OFFICIAL[role],area:s.area});
        }
    });

    /* INTERNET PIYASA */
    const marketKeys=[...new Set(
        items.map(s=>marketKey(material,s.type,size)).filter(Boolean)
    )];

    const marketRows=marketKeys
        .map(k=>MARKET[k])
        .filter(Boolean);

    let marketNote='İnternet piyasa araştırması bulunamadı.';

    if(marketRows.length){
        const min=Math.min(...marketRows.map(r=>Number(r.min)));
        const max=Math.max(...marketRows.map(r=>Number(r.max)));
        const sources=[...new Set(marketRows.flatMap(r=>r.sources||[]))];
        const ready=marketRows.every(r=>r.status==='ready');

        const marketMid=(min+max)/2;

        $('marketPrice').textContent=
            marketMid.toLocaleString('tr-TR',{
                minimumFractionDigits:2,
                maximumFractionDigits:2
            })+
            ' TL/m²';

        if(!(boxes>0 && boxPrice>0)){
            const marketMaterialBudget=grossArea*marketMid;

            tileMaterialBudget=marketMaterialBudget;

            $('materialBudget').textContent=
                money(marketMaterialBudget);
        }

        marketNote=
            'İnternet araştırması orta piyasa değeri: '+
            sources.join(', ')+
            (marketRows[0].last_checked?' · '+marketRows[0].last_checked:'')+
            (ready?' · piyasa verisi uyumlu.':' · piyasa kaynakları arasında yüksek fiyat farkı bulundu; sonuç mühendis kontrolüne alınmıştır.');
    }else{
        $('marketPrice').textContent='Veri yok';
    }

    /*
     * TOPLAM MALZEME BÜTÇESİ
     *
     * Karo fiyatı bulunmadan yalnız yardımcı malzeme toplamını
     * "toplam malzeme" diye göstermiyoruz.
     */
    const accessoryBudget=
        adhesiveTotal+
        groutTotal+
        profileTotal;

    const totalMaterialBudget=
        tileMaterialBudget>0
            ? tileMaterialBudget+accessoryBudget
            : 0;

    $('totalMaterialBudget').textContent=
        totalMaterialBudget>0
            ? money2(totalMaterialBudget)
            : '—';

    const accessoryInfoComplete=
        adhesiveTotal>0 &&
        groutTotal>0 &&
        (
            (parseInt($('profileEdges').value)||0)===0 ||
            profileTotal>0
        );

    $('totalMaterialBudgetLabel').textContent=
        accessoryInfoComplete
            ? 'Hesaplanan Malzeme Bütçesi'
            : 'Hesaplanan Malzeme Bütçesi (Kısmi)';

    /*
     * SERAMIK V4-A COST-FIRST
     *
     * Yardımcı malzemeler eksiksiz fiyatlanmışsa toplam malzeme,
     * aksi halde yalnız doğrulanmış karo bütçesi ana bütçe kabul edilir.
     *
     * ±%10 yeni bir birim fiyat değildir.
     * Kullanıcıya gösterilen yaklaşık ön bütçe aralığıdır.
     */
    const primaryBudget=
        accessoryInfoComplete && totalMaterialBudget>0
            ? totalMaterialBudget
            : tileMaterialBudget;

    const budgetMin=
        primaryBudget>0
            ? primaryBudget*0.90
            : 0;

    const budgetMax=
        primaryBudget>0
            ? primaryBudget*1.10
            : 0;

    if(primaryBudget>0){

        $('resultBudgetLabel').textContent=
            accessoryInfoComplete
                ? 'TAHMİNİ TOPLAM MALZEME BÜTÇESİ'
                : 'TAHMİNİ KARO MALZEME BÜTÇESİ';

        $('mainResult').textContent=
            money(budgetMin)+' – '+money(budgetMax);

        $('resultMid').textContent=
            'Orta tahmin: '+money(primaryBudget);

        if(accessoryInfoComplete){

            $('resultBasis').textContent=
                'Karo ve fiyatı doğrulanmış yardımcı malzemeler üzerinden ±%10 ön bütçe bandı.';

        }else if(boxPrice>0 && boxes>0){

            $('resultBasis').textContent=
                'Girdiğiniz gerçek kutu fiyatı üzerinden ±%10 ön bütçe bandı. Yardımcı malzemeler dahil olmayabilir.';

        }else{

            $('resultBasis').textContent=
                'Doğrulanmış piyasa referansı üzerinden ±%10 ön bütçe bandı. Yardımcı malzemeler eksikse dahil değildir.';
        }

    }else{

        $('resultBudgetLabel').textContent=
            'TAHMİNİ MALZEME BÜTÇESİ';

        $('mainResult').textContent=
            'Güncel fiyat verisi bekleniyor';

        $('resultMid').textContent=
            'Metraj ve satın alma miktarı hesaplandı.';

        $('resultBasis').textContent=
            'WORKSİTEM doğrulanmamış fiyatı maliyete eklemez.';
    }

    if($('leadEstimatedCost')){
        $('leadEstimatedCost').value=
            primaryBudget>0
                ? Math.round(primaryBudget)
                : '';
    }

    if($('leadEstimatedMin')){
        $('leadEstimatedMin').value=
            primaryBudget>0
                ? Math.round(budgetMin)
                : '';
    }

    if($('leadEstimatedMax')){
        $('leadEstimatedMax').value=
            primaryBudget>0
                ? Math.round(budgetMax)
                : '';
    }


    /* ISCILIK / UYGULAMA */
    const threshold=Number(SETTINGS.tile_large_threshold||500);
    const standardRate=Number(SETTINGS.tile_labor_standard_m2||450);
    const multiplier=Number(SETTINGS.tile_large_official_multiplier||1.60);

    let applicationNote='';

    if(netArea<=threshold){
        const cost=netArea*standardRate;

        $('applicationCost').textContent=money(cost);

        applicationNote=
            `İşçilik: ${netArea.toFixed(2)} m² × ${standardRate.toLocaleString('tr-TR')} TL/m².`;
    }else{
        const pricedArea=refs.reduce((sum,r)=>sum+r.area,0);

        if(
            refs.length &&
            Math.abs(pricedArea-netArea)<0.05
        ){
            const cost=refs.reduce(
                (sum,r)=>sum+(r.area*r.data.price*multiplier),
                0
            );

            $('applicationCost').textContent=money(cost);

            applicationNote=
                `500 m² üzeri: eşleşen resmî uygulama referansları ve WORKSITEM ticari fiyatlama modeli esas alınarak hesaplandı.`;
        }else{
            $('applicationCost').textContent='Mühendis kontrolü';

            applicationNote=
                '500 m² üzeri proje için tam resmî poz eşleşmesi bulunamadı; otomatik fiyat üretilmedi.';
        }
    }


    if(refs.length){
        const unique=[...new Map(refs.map(r=>[r.role,r])).values()];
        const total=refs.reduce((sum,r)=>sum+(r.area*r.data.price),0);
        const first=unique[0].data;

        $('officialBox').classList.remove('hidden');
        $('officialTitle').textContent='ÇŞİDB/YFK '+(first.period||'2026')+' resmî uygulama referansı';
        $('officialText').textContent=
            'Resmî referans pozları: '+
            unique.map(r=>r.data.poz).join(' • ')+
            '. Ticari uygulama fiyatı WORKSITEM fiyatlama modeliyle ayrıca hesaplanır.';
    }else{
        $('officialBox').classList.add('hidden');
    }

    /*
     * Lead veri sözleşmesi:
     * calculated_area yalnızca net alanı taşır.
     * Hesap ayrıntıları project_data JSON içinde tutulur.
     */
    $('leadCalculatedData').value=netArea.toFixed(2);

    $('leadProjectData').value=JSON.stringify({
        tool: 'seramik-maliyet-hesaplayici',
        version: 'v2',
        area: Number(netArea.toFixed(2)),
        tile_size: size,
        waste_rate: Number((waste*100).toFixed(2)),
        theoretical_tiles: baseTiles,
        recommended_tiles: recommended,
        estimated_boxes: boxes || null,
        tile_material_budget: tileMaterialBudget>0
            ? Number(tileMaterialBudget.toFixed(2))
            : null,
        adhesive_total: adhesiveTotal>0
            ? Number(adhesiveTotal.toFixed(2))
            : null,
        grout_total: groutTotal>0
            ? Number(groutTotal.toFixed(2))
            : null,
        profile_total: profileTotal>0
            ? Number(profileTotal.toFixed(2))
            : null,
        total_material_budget: totalMaterialBudget>0
            ? Number(totalMaterialBudget.toFixed(2))
            : null,

        estimated_cost: primaryBudget>0
            ? Math.round(primaryBudget)
            : null,

        estimated_min: primaryBudget>0
            ? Math.round(budgetMin)
            : null,

        estimated_max: primaryBudget>0
            ? Math.round(budgetMax)
            : null,

        budget_scope:
            accessoryInfoComplete
                ? 'total_material'
                : 'tile_only',

        estimated_box_reference:
            pkg.boxText || null,

        result_version: 'v4-a'
    });

    /* SERVER_VERIFIED_TILE_V4 */

    const leadForm=$('seramikLeadForm');
    const leadSubmit=leadForm
        ? leadForm.querySelector('button[type="submit"]')
        : null;

    if(leadSubmit){
        leadSubmit.disabled=true;
        leadSubmit.textContent='Hesap doğrulanıyor...';
    }

    try{

        const response=await fetch(
            '/hesaplama/seramik-maliyeti',
            {
                method:'POST',
                headers:{
                    'Content-Type':'application/json',
                    'Accept':'application/json',
                    'X-CSRF-TOKEN':
                        document.querySelector(
                            'meta[name="csrf-token"]'
                        ).content
                },
                body:JSON.stringify({
                    material,
                    mode,
                    tile_size:size,
                    waste_rate:Number(
                        (waste*100).toFixed(2)
                    ),
                    grout_mm:Number(
                        $('grout').value||0
                    ),
                    surfaces:items.map(s=>({
                        type:s.type,
                        area:s.area ?? null,
                        width:s.width ?? null,
                        height:s.height ?? null,
                        deduct:s.deduct ?? 0
                    }))
                })
            }
        );

        const data=await response.json();

        if(
            !response.ok ||
            !data.success ||
            !data.calculation_id
        ){
            throw new Error(
                data.message ||
                Object.values(data.errors||{})
                    .flat()[0] ||
                'Fiyat doğrulanamadı'
            );
        }

        $('leadCalculationId').value=
            data.calculation_id;

        $('leadCalculatedData').value=
            Number(data.area).toFixed(2);

        $('leadEstimatedCost').value=
            Number(data.estimated_cost).toFixed(2);

        $('leadEstimatedMin').value=
            Number(data.estimated_min).toFixed(2);

        $('leadEstimatedMax').value=
            Number(data.estimated_max).toFixed(2);

        /* Ana sonuç artık yalnız server verified karo bütçesi */
        $('resultBudgetLabel').textContent=
            'TAHMİNİ KARO MALZEME BÜTÇESİ';

        $('mainResult').textContent=
            money(data.estimated_min)+
            ' – '+
            money(data.estimated_max);

        $('resultMid').textContent=
            'Orta tahmin: '+
            money(data.estimated_cost);

        $('resultBasis').textContent=
            'WORKSİTEM sunucu doğrulamalı piyasa benchmarkı üzerinden ±%10 ön bütçe bandı.';

        $('materialBudget').textContent=
            money(data.estimated_cost);

        $('marketPrice').textContent=
            trNumber(data.unit_price,2)+
            ' TL/m²';

        $('recommendedPurchase').textContent=
            data.recommended_tiles+
            ' adet karo';

        $('netArea').textContent=
            trNumber(data.area,2)+
            ' m²';

        $('grossArea').textContent=
            trNumber(data.gross_area,2)+
            ' m²';

        $('recommendedTiles').textContent=
            data.recommended_tiles+
            ' adet';

        $('purchaseSummary').textContent=
            `${trNumber(data.gross_area,2)} m² satın alma alanı · `+
            `Net alan: ${trNumber(data.area,2)} m² · `+
            `Fire: %${trNumber(data.waste_rate,0)} · `+
            `${purchaseBoxReference}`;

        let pd={};

        try{
            pd=JSON.parse(
                $('leadProjectData').value||'{}'
            );
        }catch(e){}

        Object.assign(pd,{
            version:'v4-a3b',
            area:Number(data.area),
            tile_size:data.tile_size,
            waste_rate:Number(data.waste_rate),
            theoretical_tiles:
                Number(data.theoretical_tiles),
            layout_tiles:
                Number(data.layout_tiles),
            recommended_tiles:
                Number(data.recommended_tiles),
            gross_area:
                Number(data.gross_area),
            tile_material_budget:
                Number(data.estimated_cost),
            estimated_cost:
                Number(data.estimated_cost),
            estimated_min:
                Number(data.estimated_min),
            estimated_max:
                Number(data.estimated_max),
            budget_scope:'tile_only',
            calculation_mode:
                'tile_market_estimate',
            result_version:'v4-a3b'
        });

        $('leadProjectData').value=
            JSON.stringify(pd);

    }catch(error){

        /*
         * Fiyat doğrulanamazsa metraj kullanılabilir,
         * fakat CRM'e browser fiyatı gönderilmez.
         */
        $('leadCalculationId').value='';
        $('leadEstimatedCost').value='';
        $('leadEstimatedMin').value='';
        $('leadEstimatedMax').value='';

        $('resultBudgetLabel').textContent=
            'TAHMİNİ MALZEME BÜTÇESİ';

        $('mainResult').textContent=
            'Güncel fiyat verisi bekleniyor';

        $('resultMid').textContent=
