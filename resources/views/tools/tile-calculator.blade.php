function valueRange(values,digits=2){
    values=[...new Set(
        values
            .map(Number)
            .filter(v=>Number.isFinite(v) && v>0)
            .map(v=>Number(v.toFixed(4)))
    )].sort((a,b)=>a-b);

    if(!values.length) return null;

    const min=values[0];
    const max=values[values.length-1];

    return Math.abs(max-min)<0.0001
        ? trNumber(min,digits)
        : `${trNumber(min,digits)}–${trNumber(max,digits)}`;
}

function parsePieceValues(value){
    if(Number.isFinite(Number(value)) && Number(value)>0){
        return [Number(value)];
    }

    if(typeof value==='string'){
        const nums=value.match(/\d+(?:[.,]\d+)?/g);

        if(nums){
            return nums
                .map(v=>Number(v.replace(',','.')))
                .filter(v=>v>0);
        }
    }

    return [];
}

function tilePackagingResult(size,recommended,grossArea,tileArea){

    const profiles=PACKAGE_GUIDE[size]||[];

    if(!profiles.length){
        return {
            packageText:'Ambalajdan doğrulayın',
            shippingText:'Ağırlık bilgisi gerekli',
            boxText:null
        };
    }

    const pieces=[];
    const boxAreas=[];
    const boxWeights=[];
    const kgM2=[];
    const pallets=[];
    const boxCounts=[];
    const thickness=[];

    profiles.forEach(p=>{

        let profilePieces=parsePieceValues(p.pieces_box);

        if(!profilePieces.length && Number(p.box_m2)>0 && tileArea>0){
            const derived=Number(p.box_m2)/tileArea;

            if(derived>0){
                profilePieces=[Math.round(derived)];
            }
        }

        profilePieces.forEach(n=>{
            if(n>0){
                pieces.push(n);
                boxCounts.push(Math.ceil(recommended/n));
            }
        });

        if(Number(p.box_m2)>0){
            boxAreas.push(Number(p.box_m2));
        }

        if(Number(p.thickness_mm)>0){
            thickness.push(Number(p.thickness_mm));
        }

        let density=null;

        if(Number(p.box_kg)>0 && Number(p.box_m2)>0){
            density=Number(p.box_kg)/Number(p.box_m2);
            boxWeights.push(Number(p.box_kg));
        }

        if(
            !density &&
            Number(p.pallet_kg)>0 &&
            Number(p.pallet_m2)>0
        ){
            density=Number(p.pallet_kg)/Number(p.pallet_m2);

            if(Number(p.box_m2)>0){
                boxWeights.push(
                    density*Number(p.box_m2)
                );
            }
        }

        if(density){
            kgM2.push(density);
        }

        if(Number(p.pallet_m2)>0){
            pallets.push(
                Math.ceil(grossArea/Number(p.pallet_m2))
            );
        }
    });


    const packageParts=[];

    const pr=valueRange(pieces,0);
    const ar=valueRange(boxAreas,2);
    const wr=valueRange(boxWeights,1);
    const th=valueRange(thickness,1);

    if(pr) packageParts.push(`${pr} adet/kutu`);


    let shippingText='Ağırlık bilgisi gerekli';

    if(kgM2.length){

        const tonnes=kgM2.map(
            density=>grossArea*density/1000
        );

        const tonRange=valueRange(tonnes,2);
        const palletRange=valueRange(pallets,0);

        shippingText=`≈${tonRange} ton`;

        if(palletRange){
            shippingText+=` · ≈${palletRange} palet`;
        }
    }


    return {
        packageText:
            packageParts.join(' · ') ||
            'Paketleme referansı mevcut',

        shippingText,

        boxText:
            boxCounts.length
                ? `${valueRange(boxCounts,0)} kutu (referans)`
                : null
    };
}
