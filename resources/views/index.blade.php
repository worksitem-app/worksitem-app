function showRequestError(response){
 const status=$('estAiStatus');
 status.hidden=false;

 if(response.status===419){
  status.textContent='Oturum süreniz doldu. Lütfen sayfayı yenileyip tekrar deneyin.';
 }else if(response.status===422){
  status.textContent='Dosya doğrulanamadı. PDF, CSV, JPG, JPEG veya PNG biçiminde ve en fazla 10 MB dosya yükleyin.';
 }else if(response.status===429){
  status.textContent='Çok fazla analiz isteği gönderildi. Lütfen bir süre sonra tekrar deneyin.';
 }else{
  status.textContent='Analiz tamamlanamadı. Lütfen daha sonra tekrar deneyin.';
 }
}

async function executeFileAnalysis(file){
 resetCalculationState();
 const requestId=++currentRequestId;
 const controller=new AbortController();
 activeAbortController=controller;

 calcBtn.disabled=true;
 calcBtn.textContent='DOSYA ANALİZ EDİLİYOR...';
 $('estAiStatus').hidden=false;
 $('estAiStatus').textContent='Dosyadan iş kalemleri ve metrajlar analiz ediliyor...';

 const formData=new FormData();
 formData.append('project_file',file);
 formData.append('project_type',$('estProject').value);
 formData.append('quality',$('estQuality').value);

 try{
  const response=await fetch('/araclar/otomatik-kesif-fiyatlandirma/hesapla',{
   method:'POST',
   headers:{
    'X-CSRF-TOKEN':'{{ csrf_token() }}',
    'Accept':'application/json',
    'X-Requested-With':'XMLHttpRequest'
   },
   body:formData,
   signal:controller.signal
  });

  if(requestId!==currentRequestId)return;

  if(!response.ok){
   showRequestError(response);
   return;
  }

  const contentType=response.headers.get('content-type')||'';
  if(!contentType.includes('application/json')){
   $('estAiStatus').textContent='Sunucu yanıtı işlenemedi. Lütfen daha sonra tekrar deneyin.';
   return;
  }

  let data;
  try{
   data=await response.json();
  }catch(error){
   if(requestId!==currentRequestId)return;
   $('estAiStatus').textContent='Sunucu yanıtı işlenemedi. Lütfen daha sonra tekrar deneyin.';
   return;
  }

  if(requestId!==currentRequestId)return;

  if(!data||data.success===false){
   $('estAiStatus').textContent='Dosya analizi tamamlanamadı. Lütfen dosyayı kontrol edip tekrar deneyin.';
   return;
  }

  if(!Array.isArray(data.items)||data.items.length===0){
   $('estAiStatus').textContent='Dosyadan fiyatlandırılabilecek veya ölçülebilecek iş kalemi bulunamadı.';
   return;
  }
  if(data.items.some(item=>!item||typeof item!=='object'||Array.isArray(item))){
   $('estAiStatus').textContent='Analiz kalemleri okunamadı. Lütfen yeniden deneyin.';
   return;
  }

  showAiResult(data);
 }catch(error){
  if(requestId!==currentRequestId)return;
  if(error.name==='AbortError')return;
  $('estAiStatus').hidden=false;
  $('estAiStatus').textContent='Ağ bağlantısı nedeniyle analiz tamamlanamadı. Lütfen tekrar deneyin.';
 }finally{
  if(requestId===currentRequestId){
   if(activeAbortController===controller)activeAbortController=null;
   calcBtn.disabled=false;
   calcBtn.textContent=CALCULATE_LABEL;
  }
 }
}

